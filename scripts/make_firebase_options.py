#!/usr/bin/env python3
"""Generate lib/firebase_options.dart (Android) from android/app/google-services.json.
No FlutterFire CLI needed — works in Termux and in GitHub Actions.
usage: python3 scripts/make_firebase_options.py [google-services.json] [out.dart]
"""
import json, sys
src = sys.argv[1] if len(sys.argv) > 1 else "android/app/google-services.json"
out = sys.argv[2] if len(sys.argv) > 2 else "lib/firebase_options.dart"
g = json.load(open(src))
pi = g["project_info"]
client = next(c for c in g["client"] if c["client_info"]["android_client_info"]["package_name"] == "com.nexora.app")
api_key = client["api_key"][0]["current_key"]
app_id = client["client_info"]["mobilesdk_app_id"]
